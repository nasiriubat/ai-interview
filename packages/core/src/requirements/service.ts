/**
 * Requirements sessions (spec 05, contract 18): creation, the live spec, owner edits and
 * finding outcomes, versions generated by the worker, exports, GitHub push, and external
 * invitations. Every method is tenant-scoped; members see only their own sessions.
 */
export class RequirementsService {
  constructor(private readonly deps: RequirementsServiceDeps) {}

  // ---------- Sessions ----------

  async create(
    companyId: string,
    ownerUserId: string,
    input: {
      title: string;
      prompt?: string | undefined;
      path?: Path | undefined;
      templateId?: string | undefined;
      /** Accepted for the contract; the template's language governs the interview and the document. */
      language?: string | undefined;
    },
  ): Promise<RequirementsSession> {
    const { db } = this.deps;
    const template = input.templateId
      ? await db.interviewTemplate.findFirst({
          where: { id: input.templateId, status: "published", OR: [{ companyId }, { companyId: null }] },
        })
      : await this.requirementsTemplate(companyId);
    if (!template) throw new RequirementsNotFoundError("Template");
    const parsed = templateFromRow(template);

    let state = SessionStateSchema.parse({});
    const prompt = input.prompt?.trim();
    if (prompt) {
      state = {
        ...state,
        facts: mergeFacts(state.facts, [
          { kind: "spec_field", section: "overview", path: "idea", value: prompt, source: "user" },
        ]),
        coverage: parsed.coverageAreas.some((a) => a.key === "problem")
          ? {
              ...state.coverage,
              problem: {
                status: "partial",
                known: prompt.slice(0, 200),
                missing: "confirm the problem and success measure",
                followUpsUsed: 0,
              },
            }
          : state.coverage,
      };
    }
    const row = await db.session.create({
      data: {
        companyId,
        templateId: template.id,
        ownerUserId,
        sourceKind: "text",
        title: input.title.trim().slice(0, 120),
        ...(input.path ? { path: input.path } : {}),
        status: "consented",
        consentedAt: new Date(),
        state: state as Prisma.InputJsonValue,
        templateVersion: template.version,
      },
      include: { template: true },
    });
    return this.sessionView(row);
  }

  async list(companyId: string, viewer: Viewer): Promise<RequirementsListItem[]> {
    const rows = await this.deps.db.session.findMany({
      where: {
        companyId,
        ownerUserId: viewer.role === "member" ? viewer.userId : { not: null },
        template: { key: REQUIREMENTS_TEMPLATE_KEY },
        status: { not: "deleted" },
        // Template previews are owned sessions too; their participant is the previewing admin.
        OR: [{ participantId: null }, { participant: { userId: null } }],
      },
      include: { owner: { select: { email: true } }, _count: { select: { specs: true } } },
      orderBy: { createdAt: "desc" },
    });
    return rows.map((r) => {
      const state = SessionStateSchema.safeParse(r.state);
      const findings = state.success ? state.data.findings : [];
      return {
        id: r.id,
        title: r.title,
        status: r.status,
        path: pathOf(r.path),
        sourceKind: r.sourceKind,
        ownerUserId: r.ownerUserId,
        ...(r.owner ? { ownerEmail: r.owner.email } : {}),
        versions: r._count.specs,
        openFindings: findings.filter((f) => f.status === "open" || f.status === "raised").length,
        createdAt: r.createdAt,
        ...(r.endedAt ? { endedAt: r.endedAt } : {}),
      };
    });
  }

  async get(
    companyId: string,
    id: string,
    viewer: Viewer,
  ): Promise<{
    session: RequirementsSession;
    messages: ReturnType<typeof toStored>[];
    spec: LiveSpec;
    versions: SpecVersionSummary[];
    invitations: SessionInvitation[];
  }> {
    const row = await this.load(companyId, id, viewer);
    const [messages, versions, spec] = await Promise.all([
      row.status === "deleted"
        ? []
        : this.deps.db.message.findMany({ where: { sessionId: row.id }, orderBy: { seq: "asc" } }),
      this.deps.db.specVersion.findMany({ where: { sessionId: row.id }, orderBy: { version: "desc" } }),
      this.liveSpecOf(row),
    ]);
    return {
      session: this.sessionView(row),
      messages: messages.map(toStored),
      spec,
      versions: versions.map(versionSummary),
      invitations: publicInvitations(row.invitations),
    };
  }

  /** The live spec after a turn, rendered from the state the engine just persisted (or the stored one). */
  async liveSpec(companyId: string, id: string, state?: SessionState): Promise<LiveSpec> {
    const row = await this.deps.db.session.findFirst({
      where: { id, companyId },
      include: { template: true },
    });
    if (!row) throw new RequirementsNotFoundError("Session");
    return this.liveSpecOf(row, state);
  }

  async setPath(companyId: string, id: string, path: Path, viewer: Viewer): Promise<void> {
    const row = await this.load(companyId, id, viewer);
    await this.deps.db.session.update({ where: { id: row.id }, data: { path } });
  }

  /** The engine must have a path before the first turn when the template asks for one. */
  async assertTurnAllowed(companyId: string, id: string, viewer: Viewer): Promise<void> {
    const row = await this.load(companyId, id, viewer);
    if (row.template.pathSelection !== "none" && !row.path) throw new PathRequiredError();
  }

  /** "I'm done": the next turn asks the closing question (same device as the participant flow). */
  async requestCompletion(companyId: string, id: string, viewer: Viewer): Promise<void> {
    const row = await this.load(companyId, id, viewer);
    if (row.status === "completed" || row.status === "deleted") return;
    const state = { ...(row.state as Record<string, unknown>), turnCount: Number.MAX_SAFE_INTEGER >> 1 };
    await this.deps.db.session.update({ where: { id: row.id }, data: { state } });
  }

  /** A completed session becomes active again; the engine continues from the areas (FR-26). */
  async reopen(companyId: string, id: string, viewer: Viewer): Promise<void> {
    const row = await this.load(companyId, id, viewer);
    if (row.status !== "completed") return;
    const state = SessionStateSchema.parse(row.state);
    const turns = await this.deps.db.message.count({ where: { sessionId: row.id, role: "assistant" } });
    const next: SessionState = {
      ...state,
      phase: "areas",
      closingAsked: false,
      finalIssueScanDone: false,
      turnCount: Math.min(state.turnCount, turns),
    };
    await this.deps.db.session.update({
      where: { id: row.id },
      data: { status: "active", endedAt: null, state: next as Prisma.InputJsonValue },
    });
  }

  // ---------- Live spec: edits and findings ----------

  async editSection(
    companyId: string,
    id: string,
    key: string,
    markdown: string,
    userId: string,
    viewer: Viewer,
  ): Promise<LiveSpec> {
    const row = await this.load(companyId, id, viewer);
    const live = await this.liveSpecOf(row);
    const known =
      (SPEC_SECTION_KEYS as readonly string[]).includes(key) || live.sections.some((s) => s.key === key);
    if (!known) throw new InvalidSectionError(key);
    const edits = parseEdits(row.specEdits);
    const { [key]: _removed, ...rest } = edits;
    const next: SpecEdits = markdown.trim()
      ? { ...rest, [key]: { markdown, editedAt: new Date().toISOString(), editedBy: userId } }
      : rest;
    await this.deps.db.session.update({ where: { id: row.id }, data: { specEdits: next } });
    await this.appendEvent(row.id, "spec_edit", { key, chars: markdown.trim().length });
    return this.liveSpecOf({ ...row, specEdits: next });
  }

  async settleFinding(
    companyId: string,
    id: string,
    findingId: string,
    outcome: FindingOutcome,
    note: string | undefined,
    userId: string,
    viewer: Viewer,
  ): Promise<LiveSpec> {
    const row = await this.load(companyId, id, viewer);
    const state = SessionStateSchema.parse(row.state);
    const finding = state.findings.find((f) => f.id === findingId);
    if (!finding) throw new RequirementsNotFoundError("Finding");
    const findings: Finding[] = state.findings.map((f) =>
      f.id === findingId
        ? {
            ...f,
            status: outcome,
            decidedTurn: state.turnCount,
            ...(note?.trim() ? { note: note.trim() } : {}),
          }
        : f,
    );
    const next: SessionState = { ...state, findings };
    await this.deps.db.session.update({
      where: { id: row.id },
      data: { state: next as Prisma.InputJsonValue },
    });
    await this.appendEvent(row.id, "finding", { kind: "outcome", findingId, outcome, by: "owner", userId });
    return this.liveSpecOf(row, next);
  }

  // ---------- Versions ----------

  async queueVersion(
    companyId: string,
    id: string,
    userId: string,
    label: string | undefined,
    viewer: Viewer,
  ): Promise<SpecVersionSummary> {
    const { db } = this.deps;
    const row = await this.load(companyId, id, viewer);
    if (row.status === "deleted") throw new RequirementsNotFoundError("Session");
    const active = await db.specVersion.findFirst({
      where: { sessionId: row.id, status: { in: ["queued", "running"] } },
    });
    if (active) throw new SpecVersionInProgressError(active.id);
    const last = await db.specVersion.findFirst({
      where: { sessionId: row.id },
      orderBy: { version: "desc" },
      select: { version: true },
    });
    const bundleFormat = await this.bundleFormat(row);
    const version = await db.specVersion.create({
      data: {
        companyId,
        sessionId: row.id,
        version: (last?.version ?? 0) + 1,
        ...(label?.trim() ? { label: label.trim().slice(0, 120) } : {}),
        status: "queued",
        spec: {},
        specMd: "",
        bundle: { format: bundleFormat, files: [] },
        issues: [],
        stats: {},
        createdBy: userId,
      },
    });
    await this.deps.jobs.publish(
      "spec.generate",
      { versionId: version.id, companyId },
      { singletonKey: `spec:${row.id}` },
    );
    return versionSummary(version);
  }

  /** The job body: one model call over the spec state, then the stored document, markdown and bundle. */
  async runGeneration(versionId: string): Promise<void> {
    const { db, log } = this.deps;
    const version = await db.specVersion.findUniqueOrThrow({
      where: { id: versionId },
      include: { session: { include: { template: true } } },
    });
    if (version.status === "done") return;
    await db.specVersion.update({ where: { id: versionId }, data: { status: "running", error: null } });
    const session = version.session;
    try {
      const template = templateFromRow(session.template);
      const values = await this.deps.settings.resolveMany(
        ["requirements.specSections", "requirements.diagramTypes", "exports.bundleFormat"],
        this.chain(session),
      );
      const caller = await this.deps.callers.forCompany(session.companyId);
      const handoff = session.handoff ? HandoffSchema.safeParse(session.handoff) : undefined;
      const path = pathOf(session.path);
      const result = await generateSpec(
        { caller, prompts: new PrismaPromptSource(db), logger: log },
        {
          companyId: session.companyId,
          sessionId: session.id,
          title: session.title || template.name,
          language: template.language,
          ...(path ? { path } : {}),
          state: SessionStateSchema.parse(session.state),
          summary: session.summary,
          edits: parseEdits(session.specEdits),
          ...(handoff?.success ? { handoff: handoff.data } : {}),
          sections: values["requirements.specSections"] as string[],
          diagramTypes: values["requirements.diagramTypes"] as DiagramType[],
          bundleFormat: values["exports.bundleFormat"] as BundleFormat,
        },
      );
      await db.specVersion.update({
        where: { id: versionId },
        data: {
          spec: result.document,
          specMd: result.markdown,
          bundle: result.bundle,
          issues: result.issues,
          stats: result.stats,
          status: "done",
          error:
            result.generated === "fallback" ? (result.error ?? "Model call failed; live spec used") : null,
          finishedAt: new Date(),
        },
      });
      log.info("spec version generated", {
        versionId,
        sessionId: session.id,
        version: version.version,
        generated: result.generated,
      });
    } catch (err) {
      const error = err instanceof Error ? err.message : String(err);
      log.warn("spec version failed", { versionId, error });
      await db.specVersion.update({
        where: { id: versionId },
        data: { status: "failed", error, finishedAt: new Date() },
      });
      throw err;
    }
  }

  async listVersions(companyId: string, id: string, viewer: Viewer): Promise<SpecVersionSummary[]> {
    const row = await this.load(companyId, id, viewer);
    const versions = await this.deps.db.specVersion.findMany({
      where: { sessionId: row.id },
      orderBy: { version: "desc" },
    });
    return versions.map(versionSummary);
  }

  async getVersion(
    companyId: string,
    id: string,
    v: number,
    viewer: Viewer,
  ): Promise<{
    version: SpecVersionSummary;
    document: SpecDocument | null;
    markdown: string;
    bundle: AgentBundle;
    issues: Finding[];
  }> {
    const row = await this.load(companyId, id, viewer);
    const version = await this.versionRow(row.id, v);
    const document = version.status === "done" ? SpecDocumentSchema.safeParse(version.spec) : undefined;
    const bundle = AgentBundleSchema.safeParse(version.bundle);
    const issues = FindingSchema.array().safeParse(version.issues);
    return {
      version: versionSummary(version),
      document: document?.success ? document.data : null,
      markdown: version.specMd,
      bundle: bundle.success ? bundle.data : { format: "generic", files: [] },
      issues: issues.success ? issues.data : [],
    };
  }

  async diffVersions(
    companyId: string,
    id: string,
    v: number,
    other: number,
    viewer: Viewer,
  ): Promise<SpecDiff> {
    const row = await this.load(companyId, id, viewer);
    const [after, before] = await Promise.all([this.versionRow(row.id, v), this.versionRow(row.id, other)]);
    return diffSpecs(this.documentOf(before), this.documentOf(after));
  }

  async exportVersion(
    companyId: string,
    id: string,
    v: number,
    format: ExportFormat,
    viewer: Viewer,
  ): Promise<{ filename: string; contentType: string; body: Buffer | string }> {
    const row = await this.load(companyId, id, viewer);
    const version = await this.versionRow(row.id, v);
    const document = this.documentOf(version);
    const base = `${slug(row.title || document.title)}-v${version.version}`;
    if (format === "md")
      return { filename: `${base}.md`, contentType: "text/markdown; charset=utf-8", body: version.specMd };
    if (format === "json")
      return {
        filename: `${base}.json`,
        contentType: "application/json; charset=utf-8",
        body: JSON.stringify(document, null, 2),
      };
    const bundle = AgentBundleSchema.parse(version.bundle);
    return { filename: `${base}-bundle.zip`, contentType: "application/zip", body: zipFiles(bundle.files) };
  }

  async pushToGitHub(
    companyId: string,
    id: string,
    v: number,
    input: {
      repository: string;
      branch?: string | undefined;
      directory?: string | undefined;
      token: string;
      message?: string | undefined;
    },
    viewer: Viewer,
  ): Promise<{ commitUrl: string; files: number; branch: string }> {
    if (!this.deps.github) throw new GitHubNotConfiguredError();
    const row = await this.load(companyId, id, viewer);
    const version = await this.versionRow(row.id, v);
    this.documentOf(version); // must be done
    const bundle = AgentBundleSchema.parse(version.bundle);
    const result = await this.deps.github.pushFiles({
      repository: input.repository,
      ...(input.branch?.trim() ? { branch: input.branch.trim() } : {}),
      ...(input.directory?.trim() ? { directory: input.directory.trim() } : {}),
      message: nonEmpty(input.message) ?? `Specification v${version.version}: ${row.title || "requirements"}`,
      token: input.token,
      files: bundle.files,
    });
    return { commitUrl: result.commitUrl, files: result.files, branch: result.branch };
  }

  // ---------- External invitations ----------

  async invite(
    companyId: string,
    id: string,
    email: string,
    userId: string,
    viewer: Viewer,
  ): Promise<SessionInvitation> {
    const { db, crypto } = this.deps;
    const row = await this.load(companyId, id, viewer);
    if (row.status === "deleted" || row.status === "completed") throw new SessionNotOpenError(row.status);
    const to = email.trim().toLowerCase();
    const token = newToken(24);
    const tokenHash = crypto.hashToken(token);
    // One participant token per session: a new invitation replaces the previous link.
    if (row.participantId) {
      const existing = await db.participant.findUnique({ where: { id: row.participantId } });
      await db.participant.update({
        where: { id: row.participantId },
        data: { tokenHash, fields: { ...((existing?.fields ?? {}) as Record<string, string>), email: to } },
      });
    } else {
      const participant = await db.participant.create({
        data: { companyId, campaignId: null, fields: { email: to }, tokenHash },
      });
      await db.session.update({ where: { id: row.id }, data: { participantId: participant.id } });
    }
    const now = new Date();
    const invitation: StoredInvitation = {
      id: `inv_${newToken(9)}`,
      email: to,
      status: "sent",
      sentAt: now.toISOString(),
      expiresAt: new Date(now.getTime() + INVITE_DAYS * 86400_000).toISOString(),
      tokenHash,
    };
    const previous = storedInvitations(row.invitations).map((i) =>
      i.status === "revoked" ? i : { ...i, status: "revoked" as const },
    );
    const invitations = [...previous, invitation];
    await db.session.update({
      where: { id: row.id },
      data: { invitations: invitations },
    });
    const productName = await this.deps.settings.get("branding.productName", [
      { scope: "tenant", scopeId: companyId },
    ]);
    const link = `${this.deps.publicWebUrl.replace(/\/$/, "")}/p/r/${token}`;
    await this.deps.email.send({
      to,
      subject: `You are invited to describe "${row.title || "a product idea"}"`,
      text: [
        `You have been invited to answer a few questions about "${row.title || "a product idea"}" in ${productName}.`,
        "",
        `Open this link to start: ${link}`,
        "",
        `The link is personal and stays valid for ${INVITE_DAYS} days.`,
      ].join("\n"),
    });
    await this.appendEvent(row.id, "invitation", { kind: "sent", invitationId: invitation.id, by: userId });
    return publicInvitation(invitation);
  }

  async revokeInvitation(companyId: string, id: string, invId: string, viewer: Viewer): Promise<void> {
    const { db, crypto } = this.deps;
    const row = await this.load(companyId, id, viewer);
    const invitations = storedInvitations(row.invitations);
    const target = invitations.find((i) => i.id === invId);
    if (!target) throw new RequirementsNotFoundError("Invitation");
    const next = invitations.map((i) => (i.id === invId ? { ...i, status: "revoked" as const } : i));
    await db.session.update({
      where: { id: row.id },
      data: { invitations: next },
    });
    // Rotate the participant token so the emailed link stops working immediately.
    if (row.participantId) {
      const participant = await db.participant.findUnique({ where: { id: row.participantId } });
      if (participant?.tokenHash === target.tokenHash)
        await db.participant.update({
          where: { id: participant.id },
          data: { tokenHash: crypto.hashToken(newToken(24)) },
        });
    }
    await this.appendEvent(row.id, "invitation", { kind: "revoked", invitationId: invId });
  }

  /** Public arrival on an invitation link. */
  async resolveInvite(token: string): Promise<InviteView & { sessionId: string; invitationId: string }> {
    const { session, invitation } = await this.findInvitation(token);
    const values = await this.deps.settings.resolveMany(
      ["branding.productName", "campaign.consentText"],
      [{ scope: "tenant", scopeId: session.companyId }],
    );
    const consentText = values["campaign.consentText"] as string;
    const status: InviteView["status"] =
      invitation.status === "revoked"
        ? "revoked"
        : new Date(invitation.expiresAt).getTime() < Date.now()
          ? "expired"
          : session.status === "completed" || session.status === "deleted"
            ? "completed"
            : "open";
    return {
      sessionId: session.id,
      invitationId: invitation.id,
      session: {
        title: session.title,
        productName: values["branding.productName"] as string,
        purpose: session.template.objective,
        consentText,
        consentVersion: `v${createHash("sha256").update(consentText).digest("hex").slice(0, 12)}`,
        pathSelection: session.template.pathSelection,
        language: session.template.language,
      },
      status,
    };
  }

  /** The invitation token is the participant token: opening marks the invitation and hands it back. */
  async openInvite(token: string): Promise<{ participantToken: string; sessionId: string; resume: boolean }> {
    const view = await this.resolveInvite(token);
    if (view.status !== "open") throw new InviteNotOpenError(view.status);
    const { session, invitation } = await this.findInvitation(token);
    const participant = session.participantId
      ? await this.deps.db.participant.findUnique({ where: { id: session.participantId } })
      : null;
    if (participant?.tokenHash !== invitation.tokenHash) throw new InviteNotOpenError("revoked");
    if (invitation.status !== "opened") {
      const next = storedInvitations(session.invitations).map((i) =>
        i.id === invitation.id ? { ...i, status: "opened" as const, openedAt: new Date().toISOString() } : i,
      );
      await this.deps.db.session.update({
        where: { id: session.id },
        data: { invitations: next },
      });
      await this.appendEvent(session.id, "invitation", { kind: "opened", invitationId: invitation.id });
    }
    const messages = await this.deps.db.message.count({ where: { sessionId: session.id } });
    return {
      participantToken: token,
      sessionId: session.id,
      resume: session.status !== "consented" && messages > 0,
    };
  }

  // ---------- Template preview ----------

  /** A throwaway session on the template, owned by the admin, opened as a participant. */
  async preview(
    companyId: string,
    templateId: string,
    adminUserId: string,
    path?: Path,
  ): Promise<{ participantToken: string; sessionId: string }> {
    const { db, crypto } = this.deps;
    const template = await db.interviewTemplate.findFirst({
      where: { id: templateId, OR: [{ companyId }, { companyId: null }] },
    });
    if (!template) throw new RequirementsNotFoundError("Template");
    const token = newToken(24);
    const participant = await db.participant.create({
      data: {
        companyId,
        campaignId: null,
        userId: adminUserId,
        fields: {},
        tokenHash: crypto.hashToken(token),
      },
    });
    const chosen = path ?? (template.pathSelection === "none" ? null : "technical");
    const session = await db.session.create({
      data: {
        companyId,
        templateId: template.id,
        participantId: participant.id,
        ownerUserId: adminUserId,
        sourceKind: "text",
        title: "Preview",
        status: "consented",
        consentedAt: new Date(),
        path: chosen,
        templateVersion: template.version,
      },
    });
    return { participantToken: token, sessionId: session.id };
  }

  // ---------- Internals ----------

  private async load(companyId: string, id: string, viewer: Viewer): Promise<SessionRow> {
    const row = await this.deps.db.session.findFirst({
      where: { id, companyId, ownerUserId: { not: null } },
      include: { template: true },
    });
    if (!row) throw new RequirementsNotFoundError("Session");
    if (viewer.role === "member" && row.ownerUserId !== viewer.userId) throw new RequirementsForbiddenError();
    return row;
  }

  private async requirementsTemplate(companyId: string): Promise<TemplateRow | null> {
    return this.deps.db.interviewTemplate.findFirst({
      where: {
        key: REQUIREMENTS_TEMPLATE_KEY,
        status: "published",
        OR: [{ companyId }, { companyId: null }],
      },
      // Tenant copy first: a plain desc sort would put the platform row (null companyId) first in Postgres.
      orderBy: [{ companyId: { sort: "desc", nulls: "last" } }, { version: "desc" }],
    });
  }

  private chain(row: { templateId: string; companyId: string }): SettingScopeRef[] {
    return VALIDITY_KEYS.map((scope) => ({
      scope,
      scopeId: scope === "template" ? row.templateId : row.companyId,
    }));
  }

  private async liveSpecOf(row: SessionRow, state?: SessionState): Promise<LiveSpec> {
    const sections = (await this.deps.settings.get("requirements.specSections", this.chain(row))) as string[];
    return renderLiveSpec({
      title: row.title,
      path: pathOf(row.path),
      state: state ?? SessionStateSchema.parse(row.state),
      edits: parseEdits(row.specEdits),
      sections,
    });
  }

  private async bundleFormat(row: SessionRow): Promise<BundleFormat> {
    return await this.deps.settings.get("exports.bundleFormat", this.chain(row));
  }

  private sessionView(row: SessionRow): RequirementsSession {
    const state = SessionStateSchema.safeParse(row.state);
    const coverage = state.success ? state.data.coverage : {};
    const areas = templateFromRow(row.template).coverageAreas.map((a) => ({
      key: a.key,
      name: a.name,
      status: coverage[a.key]?.status ?? "untouched",
    }));
    const handoff = row.handoff ? HandoffSchema.safeParse(row.handoff) : undefined;
    return {
      id: row.id,
      title: row.title,
      status: row.status,
      path: pathOf(row.path),
      sourceKind: row.sourceKind,
      ownerUserId: row.ownerUserId,
      handoff: handoff?.success ? handoff.data : null,
      templateId: row.templateId,
      language: row.template.language,
      progress: { areas },
      phase: state.success ? state.data.phase : "areas",
      createdAt: row.createdAt,
      ...(row.startedAt ? { startedAt: row.startedAt } : {}),
      ...(row.endedAt ? { endedAt: row.endedAt } : {}),
    };
  }

  private async versionRow(sessionId: string, v: number): Promise<SpecVersion> {
    const row = await this.deps.db.specVersion.findFirst({ where: { sessionId, version: v } });
    if (!row) throw new RequirementsNotFoundError("Version");
    return row;
  }

  private documentOf(version: SpecVersion): SpecDocument {
    if (version.status !== "done") throw new SpecVersionNotReadyError(version.version, version.status);
    return SpecDocumentSchema.parse(version.spec);
  }

  private async findInvitation(
    token: string,
  ): Promise<{ session: SessionRow; invitation: StoredInvitation }> {
    const tokenHash = this.deps.crypto.hashToken(token);
    const session = await this.deps.db.session.findFirst({
      where: { invitations: { array_contains: [{ tokenHash }] } },
      include: { template: true },
    });
    const invitation = session
      ? storedInvitations(session.invitations).find((i) => i.tokenHash === tokenHash)
      : undefined;
    if (!session || !invitation) throw new RequirementsNotFoundError("Invitation");
    return { session, invitation };
  }

  private async appendEvent(sessionId: string, type: string, payload: unknown): Promise<void> {
    await this.deps.db.$transaction(async (tx) => {
      const last = await tx.sessionEvent.findFirst({
        where: { sessionId },
        orderBy: { seq: "desc" },
        select: { seq: true },
      });
      await tx.sessionEvent.create({
        data: { sessionId, seq: (last?.seq ?? 0) + 1, type, payload: payload as Prisma.InputJsonValue },
      });
    });
  }
}

// ---------- Helpers ----------

function nonEmpty(value: string | undefined): string | undefined {
  const trimmed = value?.trim();
  if (!trimmed) return undefined;
  return trimmed;
}

function pathOf(value: string | null): Path | null {
  return value === "technical" || value === "nontechnical" ? value : null;
}

export function parseEdits(value: unknown): SpecEdits {
  const parsed = SpecEditsSchema.safeParse(value ?? {});
  return parsed.success ? parsed.data : {};
}

function storedInvitations(value: unknown): StoredInvitation[] {
  if (!Array.isArray(value)) return [];
  return value.flatMap((v) => {
    const parsed = StoredInvitationSchema.safeParse(v);
    return parsed.success ? [parsed.data] : [];
  });
}

function publicInvitation(i: StoredInvitation): SessionInvitation {
  const { tokenHash: _hash, ...rest } = i;
  return rest;
}

function publicInvitations(value: unknown): SessionInvitation[] {
  return storedInvitations(value).map(publicInvitation);
}

export function versionSummary(v: SpecVersion): SpecVersionSummary {
  const stats = SpecVersionStatsSchema.safeParse(v.stats);
  return {
    id: v.id,
    version: v.version,
    ...(v.label ? { label: v.label } : {}),
    status: v.status,
    ...(v.error ? { error: v.error } : {}),
    ...(v.createdBy ? { createdBy: v.createdBy } : {}),
    createdAt: v.createdAt,
    ...(v.finishedAt ? { finishedAt: v.finishedAt } : {}),
    stats: stats.success ? stats.data : SpecVersionStatsSchema.parse({}),
  };
}

export function slug(text: string): string {
  const s = text
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return s || "spec";
}

