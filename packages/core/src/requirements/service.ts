/**
 * Requirements sessions (spec 05, contract 18): creation, the live spec, owner edits and
 * finding outcomes, versions generated by the worker, exports, GitHub push, and external
 * invitations. Every method is tenant-scoped; members see only their own sessions.
 *
 * A facade over four parts that share one `RequirementsContext`, so the API and the worker keep
 * a single class to depend on while each concern is one file under 500 lines:
 *
 * - `sessions.ts`    create, list, get, the live spec, path, completion, edits, findings, preview
 * - `diagrams.ts`   edit, add and reset the diagrams of a specification
 * - `versions.ts`    queue, generate (the worker's job body), list, get, diff
 * - `exports.ts`     file exports and the GitHub push
 * - `invitations.ts` send, revoke, resolve and open an invitation
 */
export class RequirementsService {
  private readonly sessions: RequirementsSessions;
  private readonly diagrams: RequirementsDiagrams;
  private readonly versions: RequirementsVersions;
  private readonly exports: RequirementsExports;
  private readonly invitations: RequirementsInvitations;

  constructor(deps: RequirementsServiceDeps) {
    const cx = new RequirementsContext(deps);
    this.sessions = new RequirementsSessions(cx);
    this.diagrams = new RequirementsDiagrams(cx);
    this.versions = new RequirementsVersions(cx);
    this.exports = new RequirementsExports(cx);
    this.invitations = new RequirementsInvitations(cx);
  }

  // ---------- Sessions ----------

  create(...a: Parameters<RequirementsSessions["create"]>): ReturnType<RequirementsSessions["create"]> {
    return this.sessions.create(...a);
  }
  list(...a: Parameters<RequirementsSessions["list"]>): ReturnType<RequirementsSessions["list"]> {
    return this.sessions.list(...a);
  }
  get(...a: Parameters<RequirementsSessions["get"]>): ReturnType<RequirementsSessions["get"]> {
    return this.sessions.get(...a);
  }
  liveSpec(...a: Parameters<RequirementsSessions["liveSpec"]>): ReturnType<RequirementsSessions["liveSpec"]> {
    return this.sessions.liveSpec(...a);
  }
  setPath(...a: Parameters<RequirementsSessions["setPath"]>): ReturnType<RequirementsSessions["setPath"]> {
    return this.sessions.setPath(...a);
  }
  assertAccess(
    ...a: Parameters<RequirementsSessions["assertAccess"]>
  ): ReturnType<RequirementsSessions["assertAccess"]> {
    return this.sessions.assertAccess(...a);
  }
  assertTurnAllowed(
    ...a: Parameters<RequirementsSessions["assertTurnAllowed"]>
  ): ReturnType<RequirementsSessions["assertTurnAllowed"]> {
    return this.sessions.assertTurnAllowed(...a);
  }
  requestCompletion(
    ...a: Parameters<RequirementsSessions["requestCompletion"]>
  ): ReturnType<RequirementsSessions["requestCompletion"]> {
    return this.sessions.requestCompletion(...a);
  }
  reopen(...a: Parameters<RequirementsSessions["reopen"]>): ReturnType<RequirementsSessions["reopen"]> {
    return this.sessions.reopen(...a);
  }
  editSection(
    ...a: Parameters<RequirementsSessions["editSection"]>
  ): ReturnType<RequirementsSessions["editSection"]> {
    return this.sessions.editSection(...a);
  }
  settleFinding(
    ...a: Parameters<RequirementsSessions["settleFinding"]>
  ): ReturnType<RequirementsSessions["settleFinding"]> {
    return this.sessions.settleFinding(...a);
  }
  preview(...a: Parameters<RequirementsSessions["preview"]>): ReturnType<RequirementsSessions["preview"]> {
    return this.sessions.preview(...a);
  }

  // ---------- Diagrams (FR-23) ----------

  saveDiagram(...a: Parameters<RequirementsDiagrams["save"]>): ReturnType<RequirementsDiagrams["save"]> {
    return this.diagrams.save(...a);
  }
  resetDiagram(...a: Parameters<RequirementsDiagrams["reset"]>): ReturnType<RequirementsDiagrams["reset"]> {
    return this.diagrams.reset(...a);
  }

  // ---------- Versions ----------

  queueVersion(
    ...a: Parameters<RequirementsVersions["queueVersion"]>
  ): ReturnType<RequirementsVersions["queueVersion"]> {
    return this.versions.queueVersion(...a);
  }
  runGeneration(
    ...a: Parameters<RequirementsVersions["runGeneration"]>
  ): ReturnType<RequirementsVersions["runGeneration"]> {
    return this.versions.runGeneration(...a);
  }
  listVersions(
    ...a: Parameters<RequirementsVersions["listVersions"]>
  ): ReturnType<RequirementsVersions["listVersions"]> {
    return this.versions.listVersions(...a);
  }
  getVersion(
    ...a: Parameters<RequirementsVersions["getVersion"]>
  ): ReturnType<RequirementsVersions["getVersion"]> {
    return this.versions.getVersion(...a);
  }
  diffVersions(
    ...a: Parameters<RequirementsVersions["diffVersions"]>
  ): ReturnType<RequirementsVersions["diffVersions"]> {
    return this.versions.diffVersions(...a);
  }

  // ---------- Exports ----------

  exportVersion(
    ...a: Parameters<RequirementsExports["exportVersion"]>
  ): ReturnType<RequirementsExports["exportVersion"]> {
    return this.exports.exportVersion(...a);
  }
  pushToGitHub(
    ...a: Parameters<RequirementsExports["pushToGitHub"]>
  ): ReturnType<RequirementsExports["pushToGitHub"]> {
    return this.exports.pushToGitHub(...a);
  }

  // ---------- External invitations ----------

  invite(...a: Parameters<RequirementsInvitations["invite"]>): ReturnType<RequirementsInvitations["invite"]> {
    return this.invitations.invite(...a);
  }
  revokeInvitation(
    ...a: Parameters<RequirementsInvitations["revokeInvitation"]>
  ): ReturnType<RequirementsInvitations["revokeInvitation"]> {
    return this.invitations.revokeInvitation(...a);
  }
  resolveInvite(
    ...a: Parameters<RequirementsInvitations["resolveInvite"]>
  ): ReturnType<RequirementsInvitations["resolveInvite"]> {
    return this.invitations.resolveInvite(...a);
  }
  openInvite(
    ...a: Parameters<RequirementsInvitations["openInvite"]>
  ): ReturnType<RequirementsInvitations["openInvite"]> {
    return this.invitations.openInvite(...a);
  }
}
