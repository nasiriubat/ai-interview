import { diffSpecs, generateSpec } from "@aidp/ai";
import { currentTenant } from "@aidp/db";
import {
  AgentBundleSchema,
  FindingSchema,
  HandoffSchema,
  SessionStateSchema,
  SpecDocumentSchema,
  type AgentBundle,
  type BundleFormat,
  type DiagramType,
  type Finding,
  type SpecDiff,
  type SpecDocument,
} from "@aidp/shared";
import { templateFromRow } from "../sessions/prisma-store.js";
import { PrismaPromptSource } from "../sessions/prompt-source.js";
import type { RequirementsContext } from "./context.js";
import { RequirementsNotFoundError, SpecVersionInProgressError } from "./errors.js";
import { parseEdits, pathOf, versionSummary } from "./helpers.js";
import type { RequirementsServiceDeps, SpecVersionSummary, Viewer } from "./types.js";

/** Specification versions: queued by the owner, generated by the worker (`runGeneration`), read and diffed. */
export class RequirementsVersions {
  constructor(private readonly cx: RequirementsContext) {}

  private get deps(): RequirementsServiceDeps {
    return this.cx.deps;
  }

  async queueVersion(
    companyId: string,
    id: string,
    userId: string,
    label: string | undefined,
    viewer: Viewer,
  ): Promise<SpecVersionSummary> {
    const { db } = this.deps;
    const row = await this.cx.load(companyId, id, viewer);
    if (row.status === "deleted") throw new RequirementsNotFoundError("Session");
    const active = await db.specVersion.findFirst({
      where: { sessionId: row.id, status: { in: ["queued", "running"] } },
    });
    if (active) throw new SpecVersionInProgressError(active.id);
    const last = await db.specVersion.findFirst({
      where: { sessionId: row.id },
      orderBy: { version: "desc" },
      select: { version: true },
    });
    const bundleFormat = await this.cx.bundleFormat(row);
    const version = await db.specVersion.create({
      data: {
        companyId,
        sessionId: row.id,
        version: (last?.version ?? 0) + 1,
        ...(label?.trim() ? { label: label.trim().slice(0, 120) } : {}),
        status: "queued",
        spec: {},
        specMd: "",
        bundle: { format: bundleFormat, files: [] },
        issues: [],
        stats: {},
        createdBy: userId,
      },
    });
    await this.deps.jobs.publish(
      "spec.generate",
      { versionId: version.id, companyId },
      { singletonKey: `spec:${row.id}` },
    );
    return versionSummary(version);
  }

  /** The job body: one model call over the spec state, then the stored document, markdown and bundle. */
  async runGeneration(versionId: string): Promise<void> {
    if (currentTenant() === null)
      throw new Error(
        "RequirementsService.runGeneration must be called inside a tenant context (withTenant)",
      );
    const { db, log } = this.deps;
    const version = await db.specVersion.findUniqueOrThrow({
      where: { id: versionId },
      include: { session: { include: { template: true } } },
    });
    if (version.status === "done") return;
    await db.specVersion.update({ where: { id: versionId }, data: { status: "running", error: null } });
    const session = version.session;
    try {
      const template = templateFromRow(session.template);
      const values = await this.deps.settings.resolveMany(
        ["requirements.specSections", "requirements.diagramTypes", "exports.bundleFormat"],
        this.cx.chain(session),
      );
      const caller = await this.deps.callers.forCompany(session.companyId);
      const handoff = session.handoff ? HandoffSchema.safeParse(session.handoff) : undefined;
      const path = pathOf(session.path);
      const result = await generateSpec(
        { caller, prompts: new PrismaPromptSource(db), logger: log },
        {
          companyId: session.companyId,
          sessionId: session.id,
          title: session.title || template.name,
          language: template.language,
          ...(path ? { path } : {}),
          state: SessionStateSchema.parse(session.state),
          summary: session.summary,
          edits: parseEdits(session.specEdits),
          ...(handoff?.success ? { handoff: handoff.data } : {}),
          sections: values["requirements.specSections"] as string[],
          diagramTypes: values["requirements.diagramTypes"] as DiagramType[],
          bundleFormat: values["exports.bundleFormat"] as BundleFormat,
        },
      );
      await db.specVersion.update({
        where: { id: versionId },
        data: {
          spec: result.document,
          specMd: result.markdown,
          bundle: result.bundle,
          issues: result.issues,
          stats: result.stats,
          status: "done",
          error:
            result.generated === "fallback" ? (result.error ?? "Model call failed; live spec used") : null,
          finishedAt: new Date(),
        },
      });
      log.info("spec version generated", {
        versionId,
        sessionId: session.id,
        version: version.version,
        generated: result.generated,
      });
    } catch (err) {
      const error = err instanceof Error ? err.message : String(err);
      log.warn("spec version failed", { versionId, error });
      await db.specVersion.update({
        where: { id: versionId },
        data: { status: "failed", error, finishedAt: new Date() },
      });
      throw err;
    }
  }

  async listVersions(companyId: string, id: string, viewer: Viewer): Promise<SpecVersionSummary[]> {
    const row = await this.cx.load(companyId, id, viewer);
    const versions = await this.deps.db.specVersion.findMany({
      where: { sessionId: row.id },
      orderBy: { version: "desc" },
    });
    return versions.map(versionSummary);
  }

  async getVersion(
    companyId: string,
    id: string,
    v: number,
    viewer: Viewer,
  ): Promise<{
    version: SpecVersionSummary;
    document: SpecDocument | null;
    markdown: string;
    bundle: AgentBundle;
    issues: Finding[];
  }> {
    const row = await this.cx.load(companyId, id, viewer);
    const version = await this.cx.versionRow(row.id, v);
    const document = version.status === "done" ? SpecDocumentSchema.safeParse(version.spec) : undefined;
    const bundle = AgentBundleSchema.safeParse(version.bundle);
    const issues = FindingSchema.array().safeParse(version.issues);
    return {
      version: versionSummary(version),
      document: document?.success ? document.data : null,
      markdown: version.specMd,
      bundle: bundle.success ? bundle.data : { format: "generic", files: [] },
      issues: issues.success ? issues.data : [],
    };
  }

  async diffVersions(
    companyId: string,
    id: string,
    v: number,
    other: number,
    viewer: Viewer,
  ): Promise<SpecDiff> {
    const row = await this.cx.load(companyId, id, viewer);
    const [after, before] = await Promise.all([
      this.cx.versionRow(row.id, v),
      this.cx.versionRow(row.id, other),
    ]);
    return diffSpecs(this.cx.documentOf(before), this.cx.documentOf(after));
  }
}
